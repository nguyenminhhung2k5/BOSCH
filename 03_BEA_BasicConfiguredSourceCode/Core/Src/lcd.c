/*                HÀM VẼ FONT CHỮ NHỎ 6x12 (HIỂN THỊ TRỌN VẸN 8 BYTES)         */
/* ========================================================================== */
void LCD_DrawChar6x12Ex(uint16_t x, uint16_t y, char ch, uint16_t textColor, uint16_t bgColor)
{
    if (ch < 0x20 || ch > 0x7E) ch = ' ';
    uint8_t idx = (uint8_t)(ch - 0x20);

    if (x + 6 > LCD_WIDTH || y + 12 > LCD_HEIGHT) return;

    LCD_SetWindow(x, y, x + 5, y + 11);

    LCD_DC_PORT->BSRR = LCD_DC_PIN;
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;
    LCD_SPI_Delay();

    uint8_t hiText = textColor >> 8;
    uint8_t loText = textColor & 0xFF;
    uint8_t hiBg   = bgColor >> 8;
    uint8_t loBg   = bgColor & 0xFF;

    for (uint8_t row = 0; row < 12; row++)
    {
        uint8_t r_idx = (row < 8) ? 0 : 1;
        uint8_t r_shift = (row < 8) ? row : (row - 8);
        uint8_t mask = (uint8_t)(0x80 >> r_shift);

        for (uint8_t col = 0; col < 6; col++)
        {
            uint8_t byteVal = Font6x12[idx][col * 2 + r_idx];
            if (byteVal & mask)
            {
                LCD_WriteByte_SPI(hiText);
                LCD_WriteByte_SPI(loText);
            }
            else
            {
                LCD_WriteByte_SPI(hiBg);
                LCD_WriteByte_SPI(loBg);
            }
        }
    }

    LCD_CS_PORT->BSRR = LCD_CS_PIN;
    LCD_SPI_Delay();
}

void LCD_DrawString6x12Ex(uint16_t x, uint16_t y, const char *str, uint16_t textColor, uint16_t bgColor)
{
    while (*str)
    {
        if (x + 6 > LCD_WIDTH) break;
        LCD_DrawChar6x12Ex(x, y, *str++, textColor, bgColor);
        x += 6;
    }
}

