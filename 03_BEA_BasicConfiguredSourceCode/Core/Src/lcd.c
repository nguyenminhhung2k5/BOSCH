void LCD_AddLogRecord(const char *log_text, uint16_t color)
{
    /* Đẩy các dòng log cũ trôi xuống dưới 1 dòng (các log chạy từ trên xuống) */
    for (int8_t i = MAX_CAN_LOG_LINES - 1; i > 0; i--)
    {
        strncpy(s_CanLogRecords[i], s_CanLogRecords[i - 1], sizeof(s_CanLogRecords[0]) - 1);
        s_CanLogRecords[i][sizeof(s_CanLogRecords[0]) - 1] = '\0';
        s_CanLogColors[i] = s_CanLogColors[i - 1];
    }

    /* Đưa dòng log mới nhất vào dòng đầu tiên trên cùng (index 0) */
    strncpy(s_CanLogRecords[0], log_text, sizeof(s_CanLogRecords[0]) - 1);
    s_CanLogRecords[0][sizeof(s_CanLogRecords[0]) - 1] = '\0';
    s_CanLogColors[0] = color;

    /* Vẽ lại các dòng log trôi từ trên xuống bằng Font 6x12 (Y từ 166 đến 286) */
    for (uint8_t i = 0; i < MAX_CAN_LOG_LINES; i++)
    {
        uint16_t y = 166 + i * 15;
        if (s_CanLogRecords[i][0] != '\0')
        {
            LCD_DrawString6x12Ex(16, y, s_CanLogRecords[i], s_CanLogColors[i], LCD_COLOR_BLACK);
        }
    }
}

