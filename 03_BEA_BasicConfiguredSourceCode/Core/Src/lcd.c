{
    LCD_DC_PORT->BSRR = LCD_DC_PIN;                         /* DC High = Dữ liệu */
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;         /* CS Low */
    LCD_SPI_Delay();
    LCD_WriteByte_SPI(data);
    LCD_CS_PORT->BSRR = LCD_CS_PIN;                         /* CS High */
    LCD_SPI_Delay();
}

/* ========================================================================== */
/*                KHỞI TẠO PHẦN CỨNG GPIO & CÔ LẬP TOUCH CONTROLLER           */
/* ========================================================================== */
void LCD_GPIO_Init(void)
{
    __HAL_RCC_GPIOA_CLK_ENABLE();
    __HAL_RCC_GPIOB_CLK_ENABLE();

    GPIO_InitTypeDef GPIO_InitStruct = {0};

    /* 1. MOSI (PA7) */
    GPIO_InitStruct.Pin = LCD_MOSI_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(LCD_MOSI_PORT, &GPIO_InitStruct);

    /* 2. MISO (PA6) - Kéo PULLUP để tránh thả nổi khi Touch IC ngắt */
    GPIO_InitStruct.Pin = LCD_MISO_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(LCD_MISO_PORT, &GPIO_InitStruct);

    /* 3. SCK (PB3), RST (PB2), BL (PB6), CS (PB7), DC (PB8) */
    GPIO_InitStruct.Pin = LCD_SCK_PIN | LCD_RST_PIN | LCD_BL_PIN | LCD_CS_PIN | LCD_DC_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);

    /* 4. ĐẶC BIỆT QUAN TRỌNG: Cấu hình PB9 (TP_CS) là OUTPUT và KÉO LÊN HIGH!
     * Trên board 2.8" LCD, chip Touch XPT2046 dùng chung bus SPI với màn hình.
     * Nếu PB9 bị thả nổi, mỗi khi người dùng dí tay vào hộp / màn hình, chip Touch
     * sẽ kích hoạt và chèn tín hiệu lên bus SPI làm nhiễu vỡ hình hoàn toàn! */
    GPIO_InitStruct.Pin = LCD_TP_CS_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(LCD_TP_CS_PORT, &GPIO_InitStruct);
    HAL_GPIO_WritePin(LCD_TP_CS_PORT, LCD_TP_CS_PIN, GPIO_PIN_SET); /* KHÓA TOUCH IC VĨNH VIỄN */

    /* 5. TP_IRQ (PB4) - Kéo PULLUP */
    GPIO_InitStruct.Pin = LCD_TP_IRQ_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(LCD_TP_IRQ_PORT, &GPIO_InitStruct);

    /* Mức logic mặc định ban đầu */
    HAL_GPIO_WritePin(LCD_CS_PORT, LCD_CS_PIN, GPIO_PIN_SET);
    HAL_GPIO_WritePin(LCD_DC_PORT, LCD_DC_PIN, GPIO_PIN_SET);
    HAL_GPIO_WritePin(LCD_SCK_PORT, LCD_SCK_PIN, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LCD_BL_PORT, LCD_BL_PIN, GPIO_PIN_SET);       /* Bật đèn nền */
}

/* ========================================================================== */
/*                CHU TRÌNH KHỞI ĐỘNG VÀ HIỆU CHUẨN ST7789                    */
/* ========================================================================== */
void LCD_Init(void)
{
    LCD_GPIO_Init();

    /* Reset phần cứng ST7789 theo chuẩn datasheet */
    HAL_GPIO_WritePin(LCD_RST_PORT, LCD_RST_PIN, GPIO_PIN_RESET);
    HAL_Delay(25);
    HAL_GPIO_WritePin(LCD_RST_PORT, LCD_RST_PIN, GPIO_PIN_SET);
    HAL_Delay(120);

    /* Thoát chế độ Sleep */
    LCD_Write_Command(0x11);
    HAL_Delay(120);

    /* Cấu hình hướng quét màn hình: Chiều dọc (Portrait 240x320) */
    LCD_Write_Command(0x36);
    LCD_Write_Data(0x00);

    /* Định dạng màu sắc: 16-bit RGB 565 */
    LCD_Write_Command(0x3A);
    LCD_Write_Data(0x05);

    /* Porch Setting */
    LCD_Write_Command(0xB2);
    LCD_Write_Data(0x0C); LCD_Write_Data(0x0C);
    LCD_Write_Data(0x00); LCD_Write_Data(0x33); LCD_Write_Data(0x33);

    /* Gate Control */
    LCD_Write_Command(0xB7);
    LCD_Write_Data(0x35);

    /* VCOM Setting */
    LCD_Write_Command(0xBB);
    LCD_Write_Data(0x28);

    /* LCM Control */
    LCD_Write_Command(0xC0);
    LCD_Write_Data(0x2C);

    /* VDV & VRH Command Enable */
    LCD_Write_Command(0xC2);
    LCD_Write_Data(0x01);

    /* VRH Set */
    LCD_Write_Command(0xC3);
    LCD_Write_Data(0x0B);

    /* VDV Set */
    LCD_Write_Command(0xC4);
    LCD_Write_Data(0x20);

    /* Frame Rate Control: 60Hz */
    LCD_Write_Command(0xC6);
    LCD_Write_Data(0x0F);

    /* Power Control 1 */
    LCD_Write_Command(0xD0);
    LCD_Write_Data(0xA4); LCD_Write_Data(0xA1);

    /* Bảng hiệu chuẩn Gamma Dương (Positive Gamma Correction) */
    LCD_Write_Command(0xE0);
    LCD_Write_Data(0xD0); LCD_Write_Data(0x01); LCD_Write_Data(0x08);
    LCD_Write_Data(0x0F); LCD_Write_Data(0x11); LCD_Write_Data(0x2A);
    LCD_Write_Data(0x36); LCD_Write_Data(0x55); LCD_Write_Data(0x44);
    LCD_Write_Data(0x3A); LCD_Write_Data(0x0B); LCD_Write_Data(0x06);
    LCD_Write_Data(0x11); LCD_Write_Data(0x20);

    /* Bảng hiệu chuẩn Gamma Âm (Negative Gamma Correction) */
    LCD_Write_Command(0xE1);
    LCD_Write_Data(0xD0); LCD_Write_Data(0x02); LCD_Write_Data(0x07);
    LCD_Write_Data(0x0A); LCD_Write_Data(0x0B); LCD_Write_Data(0x18);
    LCD_Write_Data(0x34); LCD_Write_Data(0x43); LCD_Write_Data(0x4A);
    LCD_Write_Data(0x2B); LCD_Write_Data(0x1B); LCD_Write_Data(0x1C);
    LCD_Write_Data(0x22); LCD_Write_Data(0x1F);

    /* Đảo màu màn hình (Display Inversion On - chuẩn cho màn ST7789 IPS) */
    LCD_Write_Command(0x21);
    HAL_Delay(10);

    /* Bật hiển thị */
    LCD_Write_Command(0x29);
    HAL_Delay(50);

    /* Xóa sạch màn hình màu đen */
    LCD_Clear(LCD_COLOR_BLACK);
}

