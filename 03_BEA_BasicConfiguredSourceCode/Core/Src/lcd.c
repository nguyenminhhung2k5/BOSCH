void LCD_DrawPixel(uint16_t x, uint16_t y, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    LCD_SetWindow(x, y, x, y);

    LCD_DC_PORT->BSRR = LCD_DC_PIN;
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;
    LCD_SPI_Delay();
    LCD_WriteByte_SPI(color >> 8);
    LCD_WriteByte_SPI(color & 0xFF);
    LCD_CS_PORT->BSRR = LCD_CS_PIN;
    LCD_SPI_Delay();
}

void LCD_FillRect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    if (x + w > LCD_WIDTH)  w = LCD_WIDTH - x;
    if (y + h > LCD_HEIGHT) h = LCD_HEIGHT - y;

    LCD_SetWindow(x, y, x + w - 1, y + h - 1);

    LCD_DC_PORT->BSRR = LCD_DC_PIN;
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;
    LCD_SPI_Delay();

    uint8_t hi = color >> 8;
    uint8_t lo = color & 0xFF;
    uint32_t total = w * h;

    for (uint32_t i = 0; i < total; i++)
    {
        LCD_WriteByte_SPI(hi);
        LCD_WriteByte_SPI(lo);
    }

    LCD_CS_PORT->BSRR = LCD_CS_PIN;
    LCD_SPI_Delay();
}

void LCD_DrawCharEx(uint16_t x, uint16_t y, char ch, uint16_t textColor, uint16_t bgColor)
{
    if (ch < 0x20 || ch > 0x7E) ch = ' ';
    uint8_t idx = ch - 0x20;

    LCD_SetWindow(x, y, x + 7, y + 15);

    LCD_DC_PORT->BSRR = LCD_DC_PIN;
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;
    LCD_SPI_Delay();

    uint8_t hiText = textColor >> 8;
    uint8_t loText = textColor & 0xFF;
    uint8_t hiBg   = bgColor >> 8;
    uint8_t loBg   = bgColor & 0xFF;

    for (uint8_t row = 0; row < 16; row++)
    {
        uint8_t line = Font8x16[idx][row];
        for (uint8_t col = 0; col < 8; col++)
        {
            if (line & (0x80 >> col))
            {
                LCD_WriteByte_SPI(hiText);
                LCD_WriteByte_SPI(loText);
            }
            else
            {
                LCD_WriteByte_SPI(hiBg);
                LCD_WriteByte_SPI(loBg);
            }
        }
    }

    LCD_CS_PORT->BSRR = LCD_CS_PIN;
    LCD_SPI_Delay();
}

void LCD_DrawChar(uint16_t x, uint16_t y, char ch)
{
    LCD_DrawCharEx(x, y, ch, s_TextColor, s_BackColor);
}

void LCD_DrawStringEx(uint16_t x, uint16_t y, const char *str, uint16_t textColor, uint16_t bgColor)
{
    while (*str)
    {
        if (x + 8 > LCD_WIDTH)
        {
            x = 0;
            y += 16;
            if (y + 16 > LCD_HEIGHT) break;
        }
        LCD_DrawCharEx(x, y, *str++, textColor, bgColor);
        x += 8;
    }
}

void LCD_DrawString(uint16_t x, uint16_t y, const char *str)
{
    LCD_DrawStringEx(x, y, str, s_TextColor, s_BackColor);
}

