/*           HÀM DELAY SPI ĐỊNH THỜI CHỐNG NHIỄU & XUYÊN ÂM ĐƯỜNG TRUYỀN      */
/* ========================================================================== */
/* Tại 168MHz CPU, 8 NOPs tương đương ~48ns, tạo xung clock SPI sạch ~10MHz,
 * hoàn toàn triệt tiêu sóng phản xạ (ringing) và đáp ứng chuẩn ST7789 */
static inline void LCD_SPI_Delay(void)
{
    __NOP(); __NOP(); __NOP(); __NOP();
    __NOP(); __NOP(); __NOP(); __NOP();
}

/* Gửi 1 byte SPI bit-banging chuẩn Mode 0 (CPOL=0, CPHA=0) */
static inline void LCD_WriteByte_SPI(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        if (data & 0x80)
        {
            LCD_MOSI_PORT->BSRR = LCD_MOSI_PIN;
        }
        else
        {
            LCD_MOSI_PORT->BSRR = (uint32_t)LCD_MOSI_PIN << 16;
        }

        LCD_SPI_Delay();
        LCD_SCK_PORT->BSRR = LCD_SCK_PIN;                   /* SCK High: ST7789 chốt data */
        LCD_SPI_Delay();
        LCD_SCK_PORT->BSRR = (uint32_t)LCD_SCK_PIN << 16;   /* SCK Low */
        data <<= 1;
    }
}

/* Gửi Command tới ST7789 */
static void LCD_Write_Command(uint8_t cmd)
{
    LCD_DC_PORT->BSRR = (uint32_t)LCD_DC_PIN << 16;         /* DC Low = Lệnh */
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;         /* CS Low */
    LCD_SPI_Delay();
    LCD_WriteByte_SPI(cmd);
    LCD_CS_PORT->BSRR = LCD_CS_PIN;                         /* CS High */
    LCD_SPI_Delay();
}

/* Gửi Data tới ST7789 */
