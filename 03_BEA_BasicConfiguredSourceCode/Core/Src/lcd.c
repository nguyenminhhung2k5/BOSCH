void LCD_SetWindow(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    LCD_Write_Command(0x2A); /* Column Addr Set */
    LCD_Write_Data(x0 >> 8);
    LCD_Write_Data(x0 & 0xFF);
    LCD_Write_Data(x1 >> 8);
    LCD_Write_Data(x1 & 0xFF);

    LCD_Write_Command(0x2B); /* Row Addr Set */
    LCD_Write_Data(y0 >> 8);
    LCD_Write_Data(y0 & 0xFF);
    LCD_Write_Data(y1 >> 8);
    LCD_Write_Data(y1 & 0xFF);

    LCD_Write_Command(0x2C); /* Memory Write */
}

void LCD_Clear(uint16_t Color)
{
    LCD_SetWindow(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1);

    LCD_DC_PORT->BSRR = LCD_DC_PIN;
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16;
    LCD_SPI_Delay();

    uint8_t hi = Color >> 8;
    uint8_t lo = Color & 0xFF;

    for (uint32_t i = 0; i < (LCD_WIDTH * LCD_HEIGHT); i++)
    {
        LCD_WriteByte_SPI(hi);
        LCD_WriteByte_SPI(lo);
    }

    LCD_CS_PORT->BSRR = LCD_CS_PIN;
    LCD_SPI_Delay();
}

