/* In bản tin CAN lên màn hình LCD (Tự động cuộn dòng) */
void LCD_DisplayCANLog(uint16_t can_id, const uint8_t *data, uint8_t is_rx)
{
    char log_buf[40];

    /* Format chuỗi log: ví dụ "RX 0A2: 04 05 00 00 00 00 2C 00" */
    sprintf(log_buf, "%s %03X: %02X %02X %02X %02X %02X %02X %02X %02X",
            is_rx ? "RX" : "TX",
            can_id,
            data[0], data[1], data[2], data[3],
            data[4], data[5], data[6], data[7]);

    uint16_t y_pos = 46 + (current_log_line - 3) * 16;

    /* Xóa nền dòng này trước khi ghi đè */
    LCD_FillRect(0, y_pos, LCD_WIDTH, 16, LCD_BLACK);

    /* Màu sắc trực quan: RX màu Cyan, TX màu Xanh lá (Green) */
    uint16_t textColor = is_rx ? LCD_CYAN : LCD_GREEN;

    LCD_DrawString(4, y_pos, log_buf, textColor, LCD_BLACK);

    /* Tăng dòng tiếp theo (Cuộn lại dòng đầu khi đầy) */
    current_log_line++;
    if (current_log_line > MAX_LOG_LINES)
    {
        current_log_line = 3;
    }
}

