/* Chuyển chân PB6 sang điều khiển màn hình LCD (Đèn nền LCD_BL) */
void LCD_Switch_To_LCD(void)
{
    HAL_GPIO_DeInit(GPIOB, GPIO_PIN_6);

    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = LCD_BL_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(LCD_BL_PORT, &GPIO_InitStruct);

    HAL_GPIO_WritePin(LCD_BL_PORT, LCD_BL_PIN, GPIO_PIN_SET); /* Bật đèn sáng */
}

/* Chuyển chân PB6 sang làm CAN2_TX nếu cần */
void LCD_Switch_To_CAN2(void)
{
    HAL_GPIO_DeInit(GPIOB, GPIO_PIN_6);

    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = GPIO_PIN_6;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_VERY_HIGH;
    GPIO_InitStruct.Alternate = GPIO_AF9_CAN2;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);
}
