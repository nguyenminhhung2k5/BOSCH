/* Giao tiếp SPI tốc độ cao bằng thanh ghi GPIO BSRR (1 chu kỳ lệnh) */
static inline void LCD_WriteByte_SPI(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        if (data & 0x80)
            LCD_MOSI_PORT->BSRR = LCD_MOSI_PIN;
        else
            LCD_MOSI_PORT->BSRR = (uint32_t)LCD_MOSI_PIN << 16;

        LCD_SCK_PORT->BSRR = LCD_SCK_PIN;          /* Clock High */
        data <<= 1;
        LCD_SCK_PORT->BSRR = (uint32_t)LCD_SCK_PIN << 16; /* Clock Low */
    }
}

/* Gửi 1 byte lệnh (Command) tới LCD */
static void LCD_Write_Command(uint8_t cmd)
{
    LCD_DC_PORT->BSRR = (uint32_t)LCD_DC_PIN << 16; /* DC Low = Lệnh */
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16; /* CS Low = Chọn chip */
    LCD_WriteByte_SPI(cmd);
    LCD_CS_PORT->BSRR = LCD_CS_PIN;                 /* CS High */
}

/* Gửi 1 byte dữ liệu (Data) tới LCD */
static void LCD_Write_Data(uint8_t data)
{
    LCD_DC_PORT->BSRR = LCD_DC_PIN;                 /* DC High = Dữ liệu */
    LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16; /* CS Low */
    LCD_WriteByte_SPI(data);
    LCD_CS_PORT->BSRR = LCD_CS_PIN;                 /* CS High */
}

